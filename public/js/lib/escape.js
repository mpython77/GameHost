/* Shared HTML escape util — XSS protection for dynamic content. */
window.GH = window.GH || {};
window.GH.escapeHTML = function escapeHTML(str) {
  if (str == null) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
};
